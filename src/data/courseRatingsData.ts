/**
 * Helper to fetch rating summary for any course slug.
 * Also maps aliases like 'manual-testing' to 'manual-qa-fundamentals'.
 */
export function getCourseRatingSummary(courseSlug: string): CourseRatingSummary {
  const normalizedSlug = courseSlug === 'manual-testing' ? 'manual-qa-fundamentals' : courseSlug;
  const summary = COURSE_RATINGS_DATA[normalizedSlug];

  if (summary) {
    return summary;
  }

  // Graceful fallback for any other course slug
  return {
    courseSlug,
    courseTitle: 'RootAccess Practical Course',
    averageRating: 4.5,
    totalRatings: 20,
    distribution: { 5: 12, 4: 6, 3: 2, 2: 0, 1: 0 },
    reviews: COURSE_RATINGS_DATA['playwright-automation'].reviews,
  };
}
