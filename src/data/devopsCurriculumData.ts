// Helper to look up a day's roadmap info
export function getRoadmapDay(dayNum: number): DevOpsRoadmapDay | undefined {
  for (const mod of DEVOPS_MODULES) {
    const found = mod.days.find((d) => d.dayNumber === dayNum);
    if (found) return found;
  }
  return undefined;
}
